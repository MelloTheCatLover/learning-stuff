// ─── тесты ───────────────────────────────────────────────
// Порядок любой, поэтому перед сравнением всё нормализуем
const norm = (gs: string[][]) => gs.map(g => [...g].sort()).sort((a, b) => a.join(",").localeCompare(b.join(",")));
const tests: [string[], string[][], string][] = [
    [["eat", "tea", "tan", "ate", "nat", "bat"], [["bat"], ["nat", "tan"], ["ate", "eat", "tea"]], "пример из условия"],
    [[""], [[""]], "одна пустая строка"],
    [["a"], [["a"]], "одна буква"],
    [["abc", "bca", "xyz", "zyx", "q"], [["abc", "bca"], ["xyz", "zyx"], ["q"]], "три группы"],
    [["", "", "a"], [["", ""], ["a"]], "пустые строки — тоже анаграммы друг друга"],
    [["ab", "ba", "abb", "bab"], [["ab", "ba"], ["abb", "bab"]], "разные длины не смешиваются"],
];
for (const [strs, want, label] of tests) {
    assert.deepEqual(norm(groupAnagrams(strs)), norm(want), label);
}
